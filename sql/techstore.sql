-- TechStore: se usa la base existente AppDistribuidas_2026_DB (tabla PRODUCTOS ya creada).
USE AppDistribuidas_2026_DB;
GO

-- 1) Columna de imagen en PRODUCTOS (idempotente)
IF COL_LENGTH('dbo.PRODUCTOS', 'IMAGENURL') IS NULL
    ALTER TABLE dbo.PRODUCTOS ADD IMAGENURL NVARCHAR(500) NOT NULL
        CONSTRAINT DF_PRODUCTOS_IMAGENURL DEFAULT '';
GO

-- 2) Facturas (requiere que PRODUCTOS.ID sea PRIMARY KEY)
IF OBJECT_ID('dbo.FACTURAS') IS NULL
CREATE TABLE dbo.FACTURAS (
    ID          INT IDENTITY(1,1) PRIMARY KEY,
    NUMERO      NVARCHAR(30)  NOT NULL UNIQUE,
    FECHA       DATE          NOT NULL,
    CLIENTE     NVARCHAR(100) NOT NULL,
    CEDULA_RUC  NVARCHAR(20)  NOT NULL,
    SUBTOTAL    DECIMAL(12,2) NOT NULL,
    IVA         DECIMAL(12,2) NOT NULL,
    TOTAL       DECIMAL(12,2) NOT NULL,
    XML         NVARCHAR(MAX) NULL
);
GO

IF OBJECT_ID('dbo.FACTURA_DETALLE') IS NULL
CREATE TABLE dbo.FACTURA_DETALLE (
    ID              INT IDENTITY(1,1) PRIMARY KEY,
    FACTURA_ID      INT NOT NULL REFERENCES dbo.FACTURAS(ID),
    PRODUCTO_ID     INT NOT NULL REFERENCES dbo.PRODUCTOS(ID),
    CANTIDAD        INT NOT NULL CHECK (CANTIDAD > 0),
    PRECIO_UNITARIO DECIMAL(10,2) NOT NULL
);
GO

